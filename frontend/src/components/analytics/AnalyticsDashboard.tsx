import { RefreshCw } from "lucide-react";
import { useCallback, useEffect, useState } from "react";
import { ApiError, api } from "../../lib/api";
import type { AnalyticsSnapshot } from "../../types";

const sentimentItems = [
  { key: "positive", label: "Positive", color: "var(--pos)" },
  { key: "neutral", label: "Neutral", color: "var(--neu)" },
  { key: "negative", label: "Negative", color: "var(--neg)" },
] as const;

export function AnalyticsDashboard() {
  const [metrics, setMetrics] = useState<AnalyticsSnapshot | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const refresh = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      setMetrics(await api.analytics());
    } catch (reason) {
      setError(reason instanceof ApiError ? reason.message : "Could not load analytics.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => { void refresh(); }, [refresh]);

  const sentimentCounts = metrics?.sentiment_counts;
  const maxSentiment = Math.max(1, ...(sentimentCounts ? Object.values(sentimentCounts) : [0]));
  const hasData = !!metrics && metrics.total_requests > 0;
  const activityMax = Math.max(1, ...(metrics?.activity.map((item) => item.requests) ?? [0]));
  const formatLabel = (label: string) => label.replaceAll("_", " ");

  return (
    <section className="analytics-panel" aria-label="Analytics dashboard" aria-busy={loading}>
      <div className="analytics-header">
        <div>
          <p className="eyebrow">Operational insights</p>
          <h2>Conversation analytics</h2>
        </div>
        <button className="btn analytics-refresh" onClick={() => void refresh()} disabled={loading}>
          <RefreshCw size={14} className={loading ? "spin" : ""} aria-hidden /> Refresh
        </button>
      </div>

      {loading && !metrics ? (
        <div className="analytics-empty" role="status"><h3>Loading analytics</h3></div>
      ) : error ? (
        <div className="analytics-empty" role="alert">
          <h3>Analytics unavailable</h3>
          <p>{error}</p>
          <button className="btn" onClick={() => void refresh()}>Try again</button>
        </div>
      ) : !hasData ? (
        <div className="analytics-empty">
          <h3>No activity yet</h3>
          <p>Request counts, response times, sentiment and provider usage will appear after the backend handles a chat or analysis request.</p>
          <small>Metrics are aggregate-only, held in memory, and reset when this backend process restarts. Up to {metrics?.retention_limit ?? 2000} recent requests are retained.</small>
        </div>
      ) : metrics && sentimentCounts ? (
        <>
          <p className="analytics-note">Actual backend requests in this running process · aggregate metrics only</p>
          <div className="kpi-grid">
            <article className="kpi-card">
              <span>Requests processed</span><strong>{metrics.total_requests}</strong>
              <small>{metrics.success_count} succeeded · {metrics.failure_count} failed</small>
            </article>
            <article className="kpi-card">
              <span>Average response time</span><strong>{metrics.average_latency_ms === null ? "--" : `${metrics.average_latency_ms.toFixed(0)} ms`}</strong>
              <small>Across chat and analysis requests</small>
            </article>
            <article className="kpi-card">
              <span>Local replies</span><strong>{metrics.source_counts.local ?? 0}</strong>
              <small>Generated by local response logic</small>
            </article>
            <article className="kpi-card">
              <span>Provider replies</span><strong>{metrics.source_counts.llm ?? 0}</strong>
              <small>Confirmed successful LLM responses</small>
            </article>
          </div>

          <div className="analytics-grid">
            <div className="analytics-card chart-card">
              <h3>Sentiment distribution</h3>
              <div className="bars" aria-label="Sentiment distribution">
                {sentimentItems.map((item) => (
                  <div key={item.key} className="bar-row">
                    <div className="bar-label"><span className="dot" style={{ background: item.color }} /><span>{item.label}</span></div>
                    <div className="bar-track"><div className="bar-fill" style={{ width: `${((sentimentCounts[item.key] ?? 0) / maxSentiment) * 100}%`, background: item.color }} /></div>
                    <strong>{sentimentCounts[item.key] ?? 0}</strong>
                  </div>
                ))}
              </div>
            </div>
            <div className="analytics-card">
              <h3>Response modes</h3>
              <ul className="mini-list">
                <li><span>Local response logic</span><strong>{metrics.source_counts.local ?? 0}</strong></li>
                <li><span>LLM response</span><strong>{metrics.source_counts.llm ?? 0}</strong></li>
                {Object.entries(metrics.provider_usage).map(([provider, count]) => (
                  <li key={provider}><span>{provider === "local" ? "Local provider" : provider}</span><strong>{count}</strong></li>
                ))}
                {Object.entries(metrics.mode_usage).map(([mode, count]) => (
                  <li key={mode}><span>{formatLabel(mode)} mode</span><strong>{count}</strong></li>
                ))}
                <li><span>Local fallbacks</span><strong>{metrics.fallback_count}</strong></li>
                <li><span>Provider failures</span><strong>{metrics.provider_failure_count}</strong></li>
              </ul>
            </div>
          </div>

          <div className="analytics-card activity-card">
            <h3>Request activity by hour</h3>
            {metrics.activity.length ? (
              <div className="activity-chart" aria-label="Requests processed per hour">
                {metrics.activity.slice(-12).map((item) => (
                  <div className="activity-column" key={item.hour} title={`${item.requests} requests · ${item.failures} failures`}>
                    <div className="activity-track">
                      <div className="activity-bar" style={{ height: `${(item.requests / activityMax) * 100}%` }} />
                    </div>
                    <span>{new Date(item.hour).toLocaleTimeString([], { hour: "numeric" })}</span>
                  </div>
                ))}
              </div>
            ) : <p className="small">No timestamped requests are available.</p>}
          </div>
        </>
      ) : null}
    </section>
  );
}

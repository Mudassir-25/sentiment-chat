"""Evaluate baselines. Run: python -m app.nlp.evaluation  (writes docs/evaluation.md + metrics.json)

Compares: majority-class baseline, rules only, TF-IDF+LogReg only, and the combined engine.
Reports accuracy, per-class precision/recall/F1, macro-F1, confusion matrix and Expected Calibration Error
on (a) the synthetic group-held-out test split and (b) the hand-written holdout.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score

from app.core.config import BACKEND_DIR
from app.nlp.dataset import load_splits
from app.nlp.sentiment import SentimentEngine
from app.nlp.rules import LABELS, analyze_rules
from app.nlp.preprocessing import preprocess

DOCS = BACKEND_DIR.parent / "docs"


def ece(conf: np.ndarray, correct: np.ndarray, bins: int = 5) -> float:
    edges = np.linspace(0, 1, bins + 1)
    total = 0.0
    for lo, hi in zip(edges[:-1], edges[1:]):
        m = (conf > lo) & (conf <= hi)
        if m.any():
            total += m.mean() * abs(correct[m].mean() - conf[m].mean())
    return float(total)


def predictions(engine: SentimentEngine, texts):
    comb, clf, rule = [], [], []
    for t in texts:
        a = engine.analyze(t)
        comb.append((a.label, a.confidence))
        rule.append((a.rules.label, max(a.rules.probabilities.values())))
        if a.classifier:
            clf.append((a.classifier.label, max(a.classifier.probabilities.values())))
    return comb, clf, rule


def score(y_true, preds) -> dict:
    y_pred = [p[0] for p in preds]
    conf = np.array([p[1] for p in preds])
    correct = np.array([a == b for a, b in zip(y_true, y_pred)], dtype=float)
    rep = classification_report(y_true, y_pred, labels=list(LABELS), output_dict=True, zero_division=0)
    return {
        "n": len(y_true),
        "accuracy": round(accuracy_score(y_true, y_pred), 4),
        "macro_f1": round(f1_score(y_true, y_pred, labels=list(LABELS), average="macro", zero_division=0), 4),
        "per_class": {k: {m: round(rep[k][m], 3) for m in ("precision", "recall", "f1-score")} for k in LABELS},
        "confusion_matrix": confusion_matrix(y_true, y_pred, labels=list(LABELS)).tolist(),
        "ece_5bin": round(ece(conf, correct), 4),
        "mean_confidence": round(float(conf.mean()), 4),
    }


def run(model_path: Path | None = None) -> dict:
    model_path = model_path or BACKEND_DIR / "models" / "sentiment.joblib"
    engine = SentimentEngine.load(model_path)
    if engine.pipeline is None:
        raise SystemExit("No trained model found. Run: python -m app.nlp.training")
    sp = load_splits()
    results: dict = {"model_meta": engine.meta, "sets": {}}
    for name in ("test", "holdout"):
        df = sp[name]
        y = list(df.label)
        comb, clf, rule = predictions(engine, df.text)
        majority = sp["train"].label.value_counts().idxmax()
        results["sets"][name] = {
            "majority_baseline": score(y, [(majority, 0.34)] * len(y)),
            "rules_only": score(y, rule),
            "tfidf_logreg_only": score(y, clf),
            "combined_engine": score(y, comb),
        }
    (DOCS).mkdir(exist_ok=True)
    (DOCS / "metrics.json").write_text(json.dumps(results, indent=2))
    (DOCS / "evaluation.md").write_text(render(results))
    return results


def render(r: dict) -> str:
    lines = ["# Evaluation results", "",
             "_Generated by `python -m app.nlp.evaluation`. Numbers below are the actual measured output of that run._", "",
             f"Model meta: `{json.dumps(r['model_meta'])}`", "",
             "- **test**: synthetic, template-generated, held out by *group* (unseen predicate phrases). Easy, in-distribution; expect optimistic numbers.",
             "- **holdout**: 60 hand-written sentences never used for fitting. A more honest (still small) estimate.",
             "- ECE = expected calibration error (5 bins). Lower is better. Confidence values are estimates, not guaranteed probabilities.", ""]
    for name, d in r["sets"].items():
        lines += [f"## {name} (n={d['majority_baseline']['n']})", "",
                  "| System | Accuracy | Macro-F1 | ECE | Mean confidence |", "|---|---|---|---|---|"]
        for sys_, m in d.items():
            lines.append(f"| {sys_} | {m['accuracy']} | {m['macro_f1']} | {m['ece_5bin']} | {m['mean_confidence']} |")
        m = d["combined_engine"]
        lines += ["", f"Combined engine per-class ({', '.join(LABELS)}):", "",
                  "| Class | Precision | Recall | F1 |", "|---|---|---|---|"]
        for k in LABELS:
            c = m["per_class"][k]
            lines.append(f"| {k} | {c['precision']} | {c['recall']} | {c['f1-score']} |")
        lines += ["", "Confusion matrix (rows = true, cols = predicted; order negative, neutral, positive):", "", "```"]
        lines += [str(row) for row in m["confusion_matrix"]]
        lines += ["```", ""]
    lines += ["## Limitations", "",
              "- Small, partly synthetic training data; vocabulary coverage is narrow.",
              "- Sarcasm, irony, idioms and domain slang are largely unsupported.",
              "- No pretrained transformer was evaluated in this run, so no claim is made about relative quality.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    res = run()
    for n, d in res["sets"].items():
        print(n, {k: (v["accuracy"], v["macro_f1"], v["ece_5bin"]) for k, v in d.items()})
